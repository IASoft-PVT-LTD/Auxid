"""Regenerates the measured part of AI-Human-Map.md from git history.

  python3 tools/authorship_map.py          rewrite the measured part
  python3 tools/authorship_map.py --check  fail if it is out of date (CI)

Lines that are not committed yet count as human, because only a commit can
carry an AI marker. AI-written work is therefore committed first, and the map
is regenerated in a second commit. Needs full git history, not a shallow clone.
"""

import argparse
import collections
import concurrent.futures
import difflib
import os
import re
import subprocess
import sys

MAP = "AI-Human-Map.md"
BEGIN = "<!-- measured: generated by tools/authorship_map.py, do not edit by hand -->"
END = "<!-- /measured -->"

# Commits that only changed licence headers and the licence text.
LICENCE_COMMITS = {
    "ef1f3e0",
    "1a658b5",
}

# Short hash -> model, for AI-written commits that were merged with a missing or
# vague marker. Commit messages can't be changed after a merge, so record it here.
RECORDED_BY_HAND = {
}

AI_NAME = re.compile(
    r"\b(claude|chatgpt|gpt|codex|copilot|cursor|gemini|deepseek|aider|devin|windsurf|grok|qwen|llama|mistral)\b", re.I)
# A tool's name alone does not say which model wrote the code.
NOT_A_MODEL = {"claude", "claude code", "chatgpt", "gpt", "codex", "copilot", "github copilot", "cursor", "cursor agent",
               "gemini", "gemini cli", "deepseek", "aider", "devin", "windsurf", "grok", "qwen", "llama", "mistral"}

AREAS = ["Library, without the OS layer", "OS layer", "Tests", "Benchmarks", "Build files and presets",
         "CI, tools and config", "README and docs"]
LIBRARY, OS_LAYER, TESTS, BENCHMARKS, BUILD, CONFIG, DOCS = AREAS
OS_MODULES = ("time", "env", "ipc", "proc", "dl")


def git(*args, check=True):
    run = subprocess.run(["git", "-c", "core.quotePath=false", "-c", "blame.ignoreRevsFile=", *args],
                         capture_output=True)
    if check and run.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed: {run.stderr.decode(errors='replace').strip()}")
    return run.stdout.decode(errors="replace")


def area_of(path):
    base = path.rsplit("/", 1)[-1]
    if path.startswith(("src/ixx/", "src/cpp/", "src/hpp/", "include/")):
        is_os = base == "auxid_win32.hpp" or any(base.startswith(f"auxid-{m}.") for m in OS_MODULES)
        return OS_LAYER if is_os else LIBRARY
    if path.startswith("tests/"):
        return TESTS
    if path.startswith("benchmarks/"):
        return BENCHMARKS
    if path.startswith("cmake/") or path in ("CMakeLists.txt", "CMakePresets.json", "src/CMakeLists.txt"):
        return BUILD
    if path.endswith(".md"):
        return DOCS
    return CONFIG


def is_counted(path):
    if path in (MAP, "LICENSE") or "/vendor/" in path or path.startswith("benchmarks/results/"):
        return False
    return not path.endswith((".png", ".ico"))


Commit = collections.namedtuple("Commit", "hash time date author subject model problem")


def ai_commits():
    """AI-marked commits by full hash, oldest first. Commits that only touch the map are left out."""
    found = []
    for record in git("log", "--reverse", "--topo-order", "--no-merges", "--date=short",
                      "--format=%H%x1f%at%x1f%ad%x1f%an%x1f%s%x1f%(trailers:key=Co-authored-by,valueonly)%x1e").split("\x1e"):
        fields = record.strip("\n").split("\x1f")
        if len(fields) != 6:
            continue
        commit, time, date, author, subject, trailers = fields
        names = []
        for line in trailers.splitlines():
            name = line.split("<")[0].strip()
            if AI_NAME.search(name) and name not in names:
                names.append(name)
        if commit[:7] in RECORDED_BY_HAND:
            names = [RECORDED_BY_HAND[commit[:7]]]
        by_ai = bool(AI_NAME.fullmatch(author.strip()))
        if not names and not by_ai:
            continue
        files = git("show", "--format=", "--name-only", commit).split()
        if files == [MAP]:
            continue
        problem = None
        if not names:
            problem = "is authored by an AI but has no Co-Authored-By trailer naming the model"
        elif any(n.lower() in NOT_A_MODEL for n in names):
            problem = f"names '{', '.join(names)}', which does not say which model wrote it"
        found.append(Commit(commit, int(time), date, author, subject, " + ".join(names) or author, problem))
    # By author time, then hash, so the order does not depend on how branches were merged.
    found.sort(key=lambda c: (c.time, c.hash))
    return collections.OrderedDict((c.hash, c) for c in found)


def blame(path, follow_copies):
    """(commit hash, text) for every counted line."""
    options = ["-w", "-M", "-C", "-C"] if follow_copies else ["-w"]
    lines = []
    commit = None
    for line in git("blame", *options, "--line-porcelain", "--", path).split("\n"):
        if line.startswith("\t"):
            lines.append((commit, line[1:]))
        elif re.match(r"[0-9a-f]{40} \d+ \d+", line):
            commit = line[:40]
    start = 0
    if lines and lines[0][1].startswith(("#!", "// auxid: trust-level")):
        start = 1
    if len(lines) > start and re.match(r"\s*(//|#)\s*Auxid: The Rigid", lines[start][1]):
        while start < len(lines) and re.match(r"\s*(//|#)", lines[start][1]):
            start += 1
    return [(h, text) for h, text in lines[start:] if text.strip()]


File = collections.namedtuple("File", "path area lines by_model strict_ai commits")


def measure(path, ai, in_head):
    if path not in in_head:
        with open(path, encoding="utf-8", errors="replace") as f:
            count = sum(1 for line in f if line.strip())
        return File(path, area_of(path), count, {}, 0, set())
    followed = blame(path, True)
    by_model = collections.Counter(ai[h].model for h, _ in followed if h in ai)
    strict_ai = sum(h in ai for h, _ in blame(path, False))
    touching = set(git("log", "--follow", "--format=%H", "--", path).split())
    commits = {h for h in touching if h in ai and h[:7] not in LICENCE_COMMITS}
    return File(path, area_of(path), len(followed), by_model, strict_ai, commits)


def percent(part, whole):
    return f"{100 * part / whole:.1f}%" if whole else "0.0%"


def existing_notes(text):
    notes = {}
    for line in text.splitlines():
        m = re.match(r"\| \[([^\]]+)\]\([^)]*\) \|.*\| ([^|]*) \|$", line)
        if m and not re.fullmatch(r"[\d,]+", m.group(2).strip()):
            notes[m.group(1)] = m.group(2).strip()
    return notes


def generate(old_text):
    if git("rev-parse", "--is-shallow-repository").strip() == "true":
        sys.exit("This needs full history. In CI, check out with fetch-depth: 0.")
    ai = ai_commits()
    problems = [f"{c.hash[:7]} \"{c.subject}\" {c.problem}" for c in ai.values() if c.problem]
    in_head = set(git("ls-tree", "-r", "--name-only", "HEAD").splitlines())
    paths = [p for p in git("ls-files").splitlines() if is_counted(p) and os.path.exists(p)]
    with concurrent.futures.ThreadPoolExecutor() as pool:
        files = list(pool.map(lambda p: measure(p, ai, in_head), paths))
    files.sort(key=lambda f: f.path)
    models = list(collections.OrderedDict.fromkeys(c.model for c in ai.values()))
    notes = existing_notes(old_text)
    out = []

    def total(selected):
        lines = sum(f.lines for f in selected)
        per = [sum(f.by_model.get(m, 0) for f in selected) for m in models]
        return lines, lines - sum(per), per

    header = " | ".join(models)
    rule = " --- |" * len(models)

    out += ["## Key stats", "", f"| | Human | {header} | All AI |", f"| --- | --- |{rule} --- |"]
    for label, selected in (("Whole repository", files),
                            ("Library only", [f for f in files if f.area in (LIBRARY, OS_LAYER)]),
                            ("Library without the OS layer", [f for f in files if f.area == LIBRARY])):
        lines, human, per = total(selected)
        cells = " | ".join(percent(p, lines) for p in per)
        out.append(f"| {label}, {lines:,} lines | **{percent(human, lines)}** | {cells} | "
                   f"**{percent(sum(per), lines)}** |")
    counts = [sum(c.model == m for c in ai.values()) for m in models]
    out += [f"| AI commits | | {' | '.join(map(str, counts))} | {len(ai)} |", ""]
    lines, _, per = total(files)
    if ai:
        out += [f"The first commit marked as AI is from {next(iter(ai.values())).date}. Percentages are rounded and may "
                "not add up to exactly 100.", ""]
    out += [f"These numbers follow moved and copied lines back to their source. Without that, AI is "
            f"{percent(sum(f.strict_ai for f in files), lines)} of the repository instead of "
            f"{percent(sum(per), lines)}.", ""]

    out += ["## By area", "", f"| Area | Lines | Human | {header} | Files with no AI code commits |",
            f"| --- | --- | --- |{rule} --- |"]
    for label, selected in [(a, [f for f in files if f.area == a]) for a in AREAS] + [("**Total**", files)]:
        lines, human, per = total(selected)
        cells = " | ".join(f"{p:,} ({percent(p, lines)})" for p in per)
        untouched = sum(not f.commits for f in selected)
        out.append(f"| {label} | {lines:,} | {human:,} ({percent(human, lines)}) | {cells} | "
                   f"{untouched} of {len(selected)} |")
    out.append("")

    out += ["## Files with AI-written lines", "",
            "Each count is the number of lines that survive today. The few human lines in files an AI created are "
            "mostly boilerplate copied from existing files.", ""]
    for a in AREAS:
        selected = [f for f in files if f.area == a and f.by_model]
        if not selected:
            continue
        noted = a == LIBRARY
        out += [f"### {a}", "", f"| File | Lines | Human | {header} |" + (" What the AI wrote |" if noted else ""),
                f"| --- | --- | --- |{rule}" + (" --- |" if noted else "")]
        for f in selected:
            human = f.lines - sum(f.by_model.values())
            cells = " | ".join(f"{f.by_model.get(m, 0):,}" for m in models)
            row = f"| [{f.path}]({f.path}) | {f.lines:,} | {human:,} ({100 * human / f.lines:.0f}%) | {cells} |"
            if noted:
                note = notes.get(f.path, "")
                if note in ("", "TODO"):
                    note = "TODO"
                    problems.append(f"{f.path} needs a \"What the AI wrote\" note in {MAP}")
                row += f" {note} |"
            out.append(row)
        out.append("")
    edited = [f for f in files if f.commits and not f.by_model]
    if edited:
        out += ["AI commits changed these files too, but none of their lines survive:", ""]
        for f in edited:
            by = ", ".join(m for m in models if any(ai[h].model == m for h in f.commits))
            out.append(f"- `{f.path}` ({by})")
        out.append("")

    out += ["## Files with no AI code commits", "",
            "The two AI relicense commits changed the licence header in most of these. Nothing else in them has an AI "
            "commit.", ""]
    for a in AREAS:
        names = [f"`{f.path}`" for f in files if f.area == a and not f.commits]
        if names:
            out.append(f"- **{a}:** " + ", ".join(names))
    out.append("")

    out += ["## AI commits", "", "Commits that only change this file are left out.", "",
            "| Commit | Date | Model | Author | Subject |", "| --- | --- | --- | --- | --- |"]
    for c in reversed(ai.values()):
        subject = c.subject.replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
        out.append(f"| `{c.hash[:7]}` | {c.date} | {c.model} | {c.author} | {subject} |")
    out.append("")
    return "\n".join(out), problems


def main():
    parser = argparse.ArgumentParser(description="Regenerate the measured part of AI-Human-Map.md.")
    parser.add_argument("--check", action="store_true", help="fail if the map is out of date instead of rewriting it")
    args = parser.parse_args()
    os.chdir(git("rev-parse", "--show-toplevel").strip())

    with open(MAP, encoding="utf-8") as f:
        old = f.read()
    if old.count(BEGIN) != 1 or old.count(END) != 1:
        sys.exit(f"{MAP} must contain the two 'measured' markers exactly once.")
    body, problems = generate(old)
    head, rest = old.split(BEGIN)
    tail = rest.split(END)[1]
    new = f"{head}{BEGIN}\n\n{body}\n{END}{tail}"

    if not args.check and new != old:
        with open(MAP, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        print(f"{MAP} updated.")
    elif not args.check:
        print(f"{MAP} is already up to date.")
    failed = bool(problems)
    if args.check and new != old:
        failed = True
        print(f"{MAP} is out of date. Run: python3 tools/authorship_map.py\n")
        sys.stdout.writelines(list(difflib.unified_diff(old.splitlines(True), new.splitlines(True), "committed",
                                                        "measured", n=0))[:80])
    for p in problems:
        print(f"problem: {p}")
    if args.check and not failed:
        print(f"{MAP} is up to date.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
